// F6: paste-ready LibreChat custom-endpoint stanza. LibreChat does not learn
// context windows from `GET /v1/models`; it reads them from `tokenConfig`. This
// route generates the whole `endpoints.custom[]` entry so a deployment can copy
// it into `librechat.yaml` (or wire an external config source to it).
import { stringify } from "yaml";

export const FRAGMENT_CONTENT_TYPE = "text/yaml; charset=utf-8";

export interface FragmentModel {
  id: string;
  context: number | null;
}

export interface FragmentOptions {
  name: string;
  baseURL: string;
  apiKey: string;
  models: FragmentModel[];
}

const HEADER = "# Generated by openproxy — paste under `endpoints:` in librechat.yaml.";

export function buildLibreChatFragment(opts: FragmentOptions): string {
  const ids: string[] = [];
  const seen = new Set<string>();
  const tokenConfig: Record<string, { context: number }> = {};
  for (const m of opts.models) {
    if (!seen.has(m.id)) {
      seen.add(m.id);
      ids.push(m.id);
    }
    if (m.context !== null) tokenConfig[m.id] = { context: m.context };
  }

  const doc = {
    endpoints: {
      custom: [
        {
          name: opts.name,
          apiKey: opts.apiKey,
          baseURL: opts.baseURL,
          models: { default: ids, fetch: true },
          titleConvo: true,
          titleModel: "current_model",
          modelDisplayLabel: opts.name,
          tokenConfig,
        },
      ],
    },
  };

  return `${HEADER}\n${stringify(doc)}`;
}

export function fragmentResponse(yaml: string): Response {
  return new Response(yaml, { headers: { "content-type": FRAGMENT_CONTENT_TYPE } });
}
